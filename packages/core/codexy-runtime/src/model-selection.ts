/**
 * Agent-scoped model selection shared by runtime entry points.
 * @module @codexydsh/runtime/model-selection
 */

import type { Context } from '@deepseek-ai/cordis'
import {
  boundContextSummary,
  createUserMessage,
  ReasoningEffortId,
  type LlmCallConfig,
} from '@deepseek-ai/dsh-llm'
import type { PromptPreparation } from './prompt.ts'
import type { PreStepDecision } from '@deepseek-ai/dsh-agent'
import type { ModelSelection, ModelSelectionRef } from '@deepseek-ai/dsh-agent'
import { requestHeaderOf } from './session.ts'
// Base prompt variables may name a route without activating a selection override.
const selectionOverrideActive = Symbol('model-selection override active')

type PreparedSelectionVariables = Readonly<Record<string, string | undefined>> & {
  readonly [selectionOverrideActive]?: boolean
}

function preparedSelection(preparation: PromptPreparation | undefined, selection: ModelSelectionRef): ModelSelection | undefined {
  if (preparation === undefined) return selection.assembled
  const variables: PreparedSelectionVariables = preparation.variables
  if (variables[selectionOverrideActive] !== true) return undefined
  const { provider, model, reasoning_effort: effort } = variables
  if (provider === undefined || model === undefined) return undefined
  return {
    provider, model,
    ...effort === undefined || effort.length === 0 ? {} : { reasoningEffort: ReasoningEffortId(effort) },
  }
}

function sameRoute(left: ModelSelection, right: ModelSelection): boolean {
  return left.provider === right.provider && left.model === right.model
}

function routeLabel(route: ModelSelection, other: ModelSelection): string {
  return route.provider === other.provider ? route.model : `${route.provider}/${route.model}`
}

function modelSwitchNotice(previous: ModelSelection, selected: ModelSelection) {
  const from = routeLabel(previous, selected)
  const to = routeLabel(selected, previous)
  return createUserMessage({
    content: [{
      type: 'text' as const,
      text: `[model changed: assistant turns above this point were generated by ${from}; the session continues with ${to}]`,
    }],
    source: {
      kind: 'model-selection',
      form: 'notice',
      summary: boundContextSummary(`${from} → ${to}`),
    },
  })
}

/**
 * Couple one mutable selection to Agent-scoped prompt assembly and request routing.
 * Prompt preparation copies the selected model before delegating, then applies
 * its provider/model pair and effort to request config so a
 * concurrent switch takes effect on a later step instead of splitting the two
 * surfaces. An absent selected effort clears any inherited effort, restoring
 * the selected model's provider/default behavior. Step preparation tokens keep
 * concurrent assemblies independent; callers without one use the latest prepared selection.
 *
 * A provider/model change appends a durable user-role notice to the next
 * admitted request. It compares the prepared selection with the latest
 * request header; effort-only changes and empty no-request decisions add no
 * notice. Failure before header persistence repeats the notice on the next
 * request.
 *
 * @param agentCtx - The selected Agent's scoped context.
 * @param selection - Mutable selection owned by the calling entry point.
 * @returns Disposer for all scoped waterfall listeners.
 */
export function installModelSelection(agentCtx: Context, selection: ModelSelectionRef): () => void {
  const disposePreparation = agentCtx.on('codexy-prompt/prepare', async (_variables, context, next) => {
    const selected = selection.current === undefined ? undefined : { ...selection.current }
    const variables = await next()
    context.signal?.throwIfAborted()
    selection.assembled = selected
    const prepared: PreparedSelectionVariables = {
      ...variables,
      [selectionOverrideActive]: selected !== undefined,
      ...selected === undefined ? {} : {
        provider: selected.provider,
        model: selected.model,
        reasoning_effort: selected.reasoningEffort ?? '',
      },
    }
    return prepared
  })
  const disposeRequest = agentCtx.on(
    'codexy-agent/request',
    async ({ promptPreparation }, next): Promise<LlmCallConfig> => {
      const resolved = await next()
      const selected = preparedSelection(promptPreparation, selection)
      if (selected === undefined) return resolved
      const { reasoningEffort: _inheritedEffort, ...withoutInheritedEffort } = resolved
      return {
        ...withoutInheritedEffort,
        provider: selected.provider,
        model: selected.model,
        ...selected.reasoningEffort === undefined
          ? {}
          : { reasoningEffort: selected.reasoningEffort },
      }
    },
  )
  const disposeNotice = agentCtx.on(
    'codexy-agent/pre-step',
    async ({ agent, messages, signal, step, promptPreparation }, next): Promise<PreStepDecision> => {
      const decision = await next()
      if (decision.kind === 'reject' || signal.aborted) return decision
      // The loop skips an empty first step and an emptied offered continuation.
      if (decision.messages.length === 0 && (step === 1 || messages.length > 0)) return decision
      const selected = preparedSelection(promptPreparation, selection)
      const previous = requestHeaderOf(agent.session)?.config
      if (selected === undefined || previous === undefined || sameRoute(selected, previous)) return decision
      return { ...decision, messages: [...decision.messages, modelSwitchNotice(previous, selected)] }
    },
    { prepend: true },
  )
  return () => {
    disposePreparation()
    disposeRequest()
    disposeNotice()
  }
}
